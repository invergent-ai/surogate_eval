"""Text-to-SQL adapter for evalscope.

Uses the BIRD Mini-Dev benchmark — 500 high-quality text-to-SQL examples
with real-world databases, multi-table JOINs, and varying difficulty.

Scoring uses LLM-as-judge to evaluate semantic SQL equivalence rather
than exact string match — two queries that return the same result set
should score equally even if they differ syntactically.

Dataset columns: question_id, db_id, question, evidence, SQL, difficulty
"""

from typing import Any, Dict

from evalscope.api.benchmark import BenchmarkMeta, DefaultDataAdapter
from evalscope.api.dataset import Sample
from evalscope.api.messages import ChatMessageUser
from evalscope.api.registry import register_benchmark
from evalscope.constants import Tags


TEXT_TO_SQL_JUDGE_PROMPT = """\
You are an expert SQL evaluator. Given a natural language question, the \
database context, a gold (reference) SQL query, and a candidate SQL query \
generated by an AI model, judge whether the candidate query is semantically \
correct.

Two queries are semantically equivalent if they would return the same \
result set on any valid instance of the given schema. Minor differences \
that do NOT affect correctness include:
- Whitespace, casing, or quoting style
- Column/table alias names
- Equivalent JOIN orderings
- `WHERE a AND b` vs `WHERE b AND a`
- `SELECT *` vs listing all columns explicitly

Differences that DO affect correctness include:
- Missing or extra columns in SELECT
- Wrong table or column references
- Missing or incorrect WHERE/JOIN/GROUP BY/HAVING/ORDER BY clauses
- Wrong aggregation functions (COUNT vs SUM, etc.)
- LIMIT differences when ORDER BY is present
- Ignoring the evidence/hints provided with the question

## Input

**Question:** {question}

**Database:** {db_id}

**Evidence/Hints:** {evidence}

**Gold SQL:**
{gold_sql}

**Candidate SQL:**
{candidate_sql}

## Instructions

Rate the candidate query on a scale of 1-10:
- 10: Semantically equivalent to the gold query (would return identical results)
- 7-9: Minor differences that likely don't affect results for most data
- 4-6: Partially correct but would return different results in some cases
- 1-3: Fundamentally wrong query

Provide your rating as a single number between 1 and 10, followed by a \
brief explanation.

Rating:"""


@register_benchmark(
    BenchmarkMeta(
        name='text_to_sql',
        pretty_name='Text-to-SQL (BIRD)',
        tags=[Tags.CODING],
        description="""\
## Overview

Text-to-SQL benchmark using BIRD Mini-Dev — real-world databases with
multi-table JOINs, aggregations, and external knowledge hints.

## Dataset

birdsql/bird_mini_dev — 500 curated examples across 11 databases with
simple, moderate, and challenging difficulty levels (SQLite variant).

## Evaluation

LLM-as-judge evaluates semantic SQL equivalence — two queries that
return the same results score equally even if syntactically different.
""",
        dataset_id='birdsql/bird_mini_dev',
        metric_list=['acc'],
        few_shot_num=0,
        train_split=None,
        eval_split='mini_dev_sqlite',
        prompt_template='',
    )
)
class TextToSQLAdapter(DefaultDataAdapter):

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._use_llm_judge = True

    def record_to_sample(self, record: Dict[str, Any]) -> Sample:
        question = record.get('question', '')
        db_id = record.get('db_id', '')
        evidence = record.get('evidence', '')
        gold_sql = record.get('SQL', '')
        difficulty = record.get('difficulty', '')

        parts = [
            f"Database: {db_id}",
            f"\nWrite a SQL query (SQLite dialect) to answer the following question.",
        ]
        if evidence:
            parts.append(f"\nHint: {evidence}")
        parts.append(f"\nQuestion: {question}")
        parts.append("\nReturn only the SQL query, nothing else.")

        prompt = "\n".join(parts)

        return Sample(
            input=[ChatMessageUser(content=prompt)],
            target=str(gold_sql),
            metadata={
                'question': question,
                'db_id': db_id,
                'evidence': evidence,
                'gold_sql': gold_sql,
                'difficulty': difficulty,
            },
        )
